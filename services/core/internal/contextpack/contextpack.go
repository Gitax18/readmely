// Package contextpack turns what an analysis found into the files an AI coding tool reads to
// understand a repository: CLAUDE.md, AGENTS.md, Cursor rules and a generic CONTEXT.md.
//
// It is deterministic: the same analysis always yields the same text, there is no model call, and
// everything is built from the facts, the file list and (when there is one) the summary. Anything
// that came from the repository is shown as inline code or plain text with line breaks and backticks
// removed, so one odd file name cannot reshape the document.
package contextpack

import (
	"fmt"
	"path"
	"sort"
	"strings"
)

// Facts is the part of the analysis facts the pack uses (ProjectFacts in contracts/core-public.yaml).
type Facts struct {
	Languages []struct {
		Name    string  `json:"name"`
		Percent float64 `json:"percent"`
	} `json:"languages"`
	Frameworks      []string `json:"frameworks"`
	PackageManagers []string `json:"package_managers"`
	EntryPoints     []string `json:"entry_points"`
	Commands        []struct {
		Name   string `json:"name"`
		Source string `json:"source"`
	} `json:"commands"`
	EnvVars     []string `json:"env_vars"`
	Services    []string `json:"services"`
	License     *string  `json:"license"`
	HasTests    bool     `json:"has_tests"`
	HasCI       bool     `json:"has_ci"`
	HasDocker   bool     `json:"has_docker"`
	Directories []struct {
		Path  string `json:"path"`
		Files int    `json:"files"`
	} `json:"directories"`
	Secrets struct {
		Count int `json:"count"`
	} `json:"secrets"`
}

// Summary is the model-written summary (ProjectSummary in the contract).
type Summary struct {
	Headline   string   `json:"headline"`
	Overview   string   `json:"overview"`
	HowItWorks []string `json:"how_it_works"`
	Components []struct {
		Path string `json:"path"`
		Role string `json:"role"`
	} `json:"components"`
}

// Hub is a file other files import most.
type Hub struct {
	Kind, Key  string
	ImportedBy int
}

// Input is everything a pack is built from.
type Input struct {
	Name        string // owner/repo
	Description string
	Facts       Facts
	Summary     *Summary // nil until one is written
	Hubs        []Hub
	Paths       []string // every readable file in the repository
}

// File is one file of a preset, at the path it belongs at in the repository.
type File struct {
	Path    string `json:"path"`
	Content string `json:"content"`
}

// Preset is one tool's flavour of the pack.
type Preset struct {
	ID          string `json:"id"`
	Label       string `json:"label"`
	Description string `json:"description"`
	Tokens      int    `json:"tokens"`
	Files       []File `json:"files"`
}

// Build returns every preset for the input, in a fixed order.
func Build(in Input) []Preset {
	body := newBody(in)
	defs := []struct {
		id, label, desc, path, title, front string
	}{
		{"claude", "Claude Code", "CLAUDE.md at the repository root.", "CLAUDE.md", "", ""},
		{"agents", "AGENTS.md", "AGENTS.md at the repository root, read by Codex, Copilot and others.", "AGENTS.md", "", ""},
		{"cursor", "Cursor", "A rule Cursor always includes: .cursor/rules/readmely.mdc.", ".cursor/rules/readmely.mdc", "",
			"---\ndescription: What this repository is and how to work in it\nalwaysApply: true\n---\n\n"},
		{"generic", "Generic", "CONTEXT.md, for any tool or for people.", "CONTEXT.md", "", ""},
	}
	out := make([]Preset, 0, len(defs))
	for _, d := range defs {
		content := d.front + body
		out = append(out, Preset{
			ID: d.id, Label: d.label, Description: d.desc, Tokens: EstimateTokens(content),
			Files: []File{{Path: d.path, Content: content}},
		})
	}
	return out
}

// EstimateTokens is a rough count (four characters to a token), enough to size a context window.
func EstimateTokens(s string) int { return (len(s) + 3) / 4 }

// inline makes a repository-derived value safe to put on one line of markdown.
func inline(s string) string {
	s = strings.Map(func(r rune) rune {
		if r < ' ' || r == 0x7f || r == '`' {
			return -1
		}
		return r
	}, s)
	return strings.TrimSpace(s)
}

func code(s string) string { return "`" + inline(s) + "`" }

func newBody(in Input) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }

	w("# %s\n\n", inline(in.Name))
	w("_Context for AI coding tools, generated by Readmely from the repository. Check it against the code; edit freely._\n\n")

	w("## What this project is\n\n")
	switch {
	case in.Summary != nil:
		w("%s\n\n%s\n\n", inline(in.Summary.Headline), inline(in.Summary.Overview))
		if len(in.Summary.HowItWorks) > 0 {
			w("How it works:\n\n")
			for _, s := range in.Summary.HowItWorks {
				w("- %s\n", inline(s))
			}
			w("\n")
		}
	case in.Description != "":
		w("%s\n\n", inline(in.Description))
	default:
		w("No description is available.\n\n")
	}

	w("## Stack\n\n")
	if len(in.Facts.Languages) > 0 {
		parts := make([]string, 0, len(in.Facts.Languages))
		for _, l := range in.Facts.Languages {
			parts = append(parts, fmt.Sprintf("%s (%.0f%%)", inline(l.Name), l.Percent))
		}
		w("- Languages: %s\n", strings.Join(parts, ", "))
	}
	if len(in.Facts.Frameworks) > 0 {
		w("- Built with: %s\n", joinInline(in.Facts.Frameworks))
	}
	if len(in.Facts.PackageManagers) > 0 {
		w("- Package managers: %s\n", joinInline(in.Facts.PackageManagers))
	}
	if len(in.Facts.Services) > 0 {
		w("- Services in the compose file: %s\n", joinInline(in.Facts.Services))
	}
	w("\n")

	w("## Layout\n\n")
	for _, d := range in.Facts.Directories {
		label := code(d.Path + dirSuffix(d.Path, in.Paths))
		if d.Path == "." {
			label = "files at the repository root"
		}
		w("- %s: %s\n", label, plural(d.Files, "file"))
	}
	w("\n")
	if len(in.Facts.EntryPoints) > 0 {
		w("Start reading at:\n\n")
		for _, e := range in.Facts.EntryPoints {
			w("- %s\n", code(e))
		}
		w("\n")
	}
	if in.Summary != nil && len(in.Summary.Components) > 0 {
		w("Key files and directories:\n\n")
		for _, c := range in.Summary.Components {
			w("- %s: %s\n", code(c.Path), inline(c.Role))
		}
		w("\n")
	}
	if len(in.Hubs) > 0 {
		w("Most imported (changes here reach the most code):\n\n")
		for _, h := range in.Hubs {
			w("- %s, by %s\n", code(h.Key), plural(h.ImportedBy, "file"))
		}
		w("\n")
	}

	w("## Commands\n\n")
	found, typical := commands(in)
	if len(found) > 0 {
		w("Found in the repository:\n\n")
		for _, c := range found {
			w("- %s (from %s)\n", code(c.name), code(c.source))
		}
		w("\n")
	}
	if len(typical) > 0 {
		w("Typical for this stack (not found in the repository; check before relying on them):\n\n")
		for _, c := range typical {
			w("- %s\n", code(c))
		}
		w("\n")
	}
	if len(found) == 0 && len(typical) == 0 {
		w("No build, run or test commands were found.\n\n")
	}

	if len(in.Facts.EnvVars) > 0 {
		w("## Settings\n\nThe code reads these environment variables:\n\n")
		for _, v := range in.Facts.EnvVars {
			w("- %s\n", code(v))
		}
		w("\n")
	}

	w("## Conventions\n\n")
	for _, c := range conventions(in) {
		w("- %s\n", c)
	}
	w("\n")

	w("## Working in this repository\n\n")
	w("- Read the entry points and the key files above before changing anything.\n")
	w("- Match the style of the surrounding code; use the formatter and linter the repository already configures.\n")
	if in.Facts.HasTests {
		w("- Run the tests before and after a change, and add one for new behaviour.\n")
	} else {
		w("- No tests were found. Say so before a risky change, and prefer small, reversible steps.\n")
	}
	w("- Never commit secrets or real credentials.")
	if in.Facts.Secrets.Count > 0 {
		w(" Readmely found %d secret-like values in this repository; they were left out of this file. Do not copy them anywhere.", in.Facts.Secrets.Count)
	}
	w("\n")
	if in.Facts.License != nil {
		w("- Licence: %s.\n", inline(*in.Facts.License))
	}
	return b.String()
}

func plural(n int, noun string) string {
	if n == 1 {
		return "1 " + noun
	}
	return fmt.Sprintf("%d %ss", n, noun)
}

func joinInline(items []string) string {
	out := make([]string, 0, len(items))
	for _, i := range items {
		out = append(out, inline(i))
	}
	return strings.Join(out, ", ")
}

// dirSuffix adds a slash to a name that is a directory (it has files below it).
func dirSuffix(name string, paths []string) string {
	prefix := name + "/"
	for _, p := range paths {
		if strings.HasPrefix(p, prefix) {
			return "/"
		}
	}
	return ""
}

type command struct{ name, source string }

// commands returns what the repository itself defines, and the usual ones for its stack that it does
// not define. The first are facts; the second are labelled as guesses.
func commands(in Input) (found []command, typical []string) {
	haveTest, haveBuild := false, false
	for _, c := range in.Facts.Commands {
		found = append(found, command{c.Name, c.Source})
		n := strings.ToLower(c.Name)
		haveTest = haveTest || strings.HasSuffix(n, " test") || strings.Contains(n, "test")
		haveBuild = haveBuild || strings.HasSuffix(n, " build")
	}
	langs := map[string]bool{}
	for _, l := range in.Facts.Languages {
		langs[l.Name] = true
	}
	managers := map[string]bool{}
	for _, m := range in.Facts.PackageManagers {
		managers[m] = true
	}
	frameworks := map[string]bool{}
	for _, f := range in.Facts.Frameworks {
		frameworks[f] = true
	}
	if langs["Go"] {
		if !haveBuild {
			typical = append(typical, "go build ./...")
		}
		if !haveTest {
			typical = append(typical, "go test ./...")
		}
	}
	if langs["Python"] {
		switch {
		case managers["uv"]:
			typical = append(typical, "uv sync")
			if !haveTest && frameworks["pytest"] {
				typical = append(typical, "uv run pytest")
			}
		case managers["poetry"]:
			typical = append(typical, "poetry install")
			if !haveTest && frameworks["pytest"] {
				typical = append(typical, "poetry run pytest")
			}
		default:
			typical = append(typical, "pip install -r requirements.txt")
			if !haveTest && frameworks["pytest"] {
				typical = append(typical, "pytest")
			}
		}
	}
	for _, m := range []string{"pnpm", "yarn", "bun", "npm"} {
		if managers[m] {
			typical = append(typical, m+" install")
			break
		}
	}
	return found, typical
}

func conventions(in Input) []string {
	has := map[string]bool{}
	for _, p := range in.Paths {
		base := path.Base(p)
		switch {
		case strings.HasPrefix(base, ".golangci"):
			has["golangci-lint"] = true
		case strings.HasPrefix(base, ".eslintrc") || strings.HasPrefix(base, "eslint.config"):
			has["ESLint"] = true
		case strings.HasPrefix(base, ".prettierrc") || strings.HasPrefix(base, "prettier.config"):
			has["Prettier"] = true
		case base == ".editorconfig":
			has["EditorConfig"] = true
		case base == "ruff.toml" || base == ".ruff.toml":
			has["Ruff"] = true
		case base == ".pre-commit-config.yaml":
			has["pre-commit"] = true
		case base == "tsconfig.json":
			has["TypeScript"] = true
		}
	}
	for _, f := range in.Facts.Frameworks {
		switch f {
		case "Ruff", "ESLint", "Prettier", "Vitest", "Jest", "pytest", "Testify", "Playwright":
			has[f] = true
		}
	}
	tools := make([]string, 0, len(has))
	for t := range has {
		tools = append(tools, t)
	}
	sort.Strings(tools)
	var out []string
	if len(tools) > 0 {
		out = append(out, "Tooling configured: "+strings.Join(tools, ", ")+".")
	}
	yn := func(b bool) string {
		if b {
			return "yes"
		}
		return "no"
	}
	out = append(out, fmt.Sprintf("Tests: %s. Continuous integration: %s. Docker: %s.", yn(in.Facts.HasTests), yn(in.Facts.HasCI), yn(in.Facts.HasDocker)))
	return out
}
